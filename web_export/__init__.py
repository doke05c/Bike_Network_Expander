"""Writes the web data for the Bikeable Radius map (UrbanBlogs posts/nyc_directed_network.html).

Everything goes into one directory in the UrbanBlogs checkout, <urbanblogs>/src/bike_network/, which this repo owns:

    README.txt         what this is and how to regenerate it (.txt: Eleventy would publish a .md as a page)
    manifest.json      where the data came from (commit, GeoPackage, counts)
    network.bin.gz     the routing network (see pack.py / network_format.js)
    network_format.js  the browser decoder for network.bin.gz; ships with the data so reader and writer always match
    empty.pbf          0-byte tile the host serves for streetless areas (see UrbanBlogs netlify.toml)
    tiles/{z}/{x}/{y}.pbf  the network drawn as vector tiles (see tiles.py)

The directory is built in <urbanblogs>/.bike_network.tmp/ (outside src/, so Eleventy's dev server doesn't copy a half-written
run) and swapped in at the end, so a failed run leaves the old one untouched.
"""
import datetime
import json
import os
import shutil
import subprocess
import time

from . import pack, tiles

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_SUBDIR = os.path.join('src', 'bike_network')

README = """Generated by Bike_Network_Expander - do not edit

Map data for posts/nyc_directed_network.html (the Bikeable Radius map). Everything in this directory is written by
https://github.com/doke05c/Bike_Network_Expander and is replaced as a whole on every run, so hand edits get lost.

Regenerate (in a Bike_Network_Expander checkout):

    python route_test.py --urbanblogs /path/to/UrbanBlogs

then commit this directory in UrbanBlogs. manifest.json records which commit and GeoPackage produced it.

The page reads these fields from network.bin.gz: multipliers, subs, sub_colors, sub_widths, names, legend, and the
per-segment columns nf, nt, wf, wr, name, sub, coords. Renaming or removing one needs a matching page change.
"""


def _git_commit():
    try:
        sha = subprocess.run(['git', 'rev-parse', 'HEAD'], cwd=HERE, capture_output=True, text=True, check=True).stdout.strip()
        dirty = subprocess.run(['git', 'status', '--porcelain', '--untracked-files=no'], cwd=HERE,
                               capture_output=True, text=True, check=True).stdout.strip()
        return sha + ('-dirty' if dirty else '')
    except (OSError, subprocess.CalledProcessError):
        return None


def export_web(export, urbanblogs_dir, source=None, merge=True):
    """write the network export (the dict route_test.py builds) into <urbanblogs_dir>/src/bike_network/.
    source: name of the input GeoPackage, recorded in manifest.json. returns the output directory"""
    out_dir = os.path.join(urbanblogs_dir, OUT_SUBDIR)
    tmp_dir = os.path.join(urbanblogs_dir, '.bike_network.tmp')   # same filesystem as out_dir, so the swap is a rename
    old_dir = os.path.join(urbanblogs_dir, '.bike_network.old')
    shutil.rmtree(tmp_dir, ignore_errors=True)
    os.makedirs(tmp_dir)
    t0 = time.time()

    gz, raw_len = pack.pack(export)   # raises if anything doesn't round-trip
    with open(os.path.join(tmp_dir, 'network.bin.gz'), 'wb') as f:
        f.write(gz)
    n_seg = len(export['nf'])
    print(f'web export: packed {n_seg} segments: {raw_len} bytes raw, {len(gz)} gzipped ({time.time() - t0:.1f}s)')

    features, n_lines = tiles.network_features(export['sub'], export['nf'], export['nt'], export['coords'],
                                               len(export['subs']), merge=merge)
    n_tiles, n_bytes = tiles.write_tiles(features, os.path.join(tmp_dir, 'tiles'))
    print(f'web export: {n_lines} lines -> {n_tiles} tiles ({n_bytes / 1e6:.1f} MB) ({time.time() - t0:.1f}s)')

    shutil.copyfile(os.path.join(HERE, 'network_format.js'), os.path.join(tmp_dir, 'network_format.js'))
    open(os.path.join(tmp_dir, 'empty.pbf'), 'wb').close()
    with open(os.path.join(tmp_dir, 'README.txt'), 'w', encoding='utf-8') as f:
        f.write(README)
    manifest = {
        'generator': 'Bike_Network_Expander',
        'commit': _git_commit(),
        'source': source,
        'generated_at': datetime.datetime.now(datetime.timezone.utc).isoformat(timespec='seconds'),
        'format_version': pack.VERSION,
        'segments': n_seg,
        'tile_lines': n_lines,
        'merged': merge,
        'tiles': n_tiles,
        'maxzoom': tiles.MAXZOOM,
    }
    with open(os.path.join(tmp_dir, 'manifest.json'), 'w', encoding='utf-8') as f:
        json.dump(manifest, f, indent=2)
        f.write('\n')

    # swap the new directory in
    os.makedirs(os.path.dirname(out_dir), exist_ok=True)
    shutil.rmtree(old_dir, ignore_errors=True)
    if os.path.exists(out_dir):
        os.rename(out_dir, old_dir)
    os.rename(tmp_dir, out_dir)
    shutil.rmtree(old_dir, ignore_errors=True)
    print(f'web export: wrote {out_dir}')
    return out_dir
